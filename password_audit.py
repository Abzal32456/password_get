#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
password_audit.py — демонстрационный генератор словаря паролей для САМОаудита.

Назначение: показать, насколько предсказуемо персональные данные превращаются
в «пароль». Скармливаешь СВОИ данные (имя, год рождения, ник, увлечения) —
получаешь список кандидатов. Если твой реальный пароль оказался в этом списке,
вывод очевиден: пароль построен по шаблону, который любой генератор воспроизводит
за миллисекунды.

Это ровно тот принцип, по которому работают атаки по словарю: злоумышленник
не угадывает 10^18 комбинаций, он генерирует несколько тысяч *осмысленных*
кандидатов из твоих же публичных данных и проверяет их против украденного хеша.

Запуск:
    python3 -I password_audit.py
(флаг -I изолирует интерпретатор; хорошая привычка при запуске чужого кода)
"""

import re
import itertools
import datetime


# ---------------------------------------------------------------------------
# 1. ТРАНСЛИТЕРАЦИЯ (кириллица -> латиница)
# ---------------------------------------------------------------------------
# Люди с русскими именами почти всегда пишут пароль латиницей: "Дмитрий" -> "dmitriy".
# Это первый шаг нормализации: приводим ввод к тому виду, в котором он реально
# попадёт в поле пароля.

TRANSLIT_MAP = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "e",
    "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
    "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
    "ф": "f", "х": "h", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "sch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
}


def transliterate(text: str) -> str:
    """Переводит кириллицу в латиницу посимвольно. Латинские символы проходят насквозь."""
    return "".join(TRANSLIT_MAP.get(ch, ch) for ch in text.lower())


# ---------------------------------------------------------------------------
# 2. LEETSPEAK — замена букв на похожие цифры/символы
# ---------------------------------------------------------------------------
# Классическое заблуждение: "я заменил a на 4, теперь пароль стойкий".
# Нет. Таких замен ~десяток, и генератор перебирает ВСЕ их сочетания.

LEET_MAP = {
    "a": ["a", "4", "@"],
    "e": ["e", "3"],
    "i": ["i", "1", "!"],
    "o": ["o", "0"],
    "s": ["s", "5", "$"],
    "t": ["t", "7"],
}


def leet_variants(word: str, max_variants: int = 32):
    """
    Генерирует все leet-мутации слова через ДЕКАРТОВО ПРОИЗВЕДЕНИЕ.

    Комбинаторика: для каждой буквы есть список вариантов. Если в слове
    k «мутируемых» букв с числом вариантов v1, v2, ..., vk, то общее число
    комбинаций = v1 * v2 * ... * vk (произведение, а не сумма!).

    Пример: "pass" -> p:[p], a:[a,4,@], s:[s,5,$], s:[s,5,$]
    = 1 * 3 * 3 * 3 = 27 вариантов из одного короткого слова.

    itertools.product как раз и считает это декартово произведение.
    max_variants обрезает взрыв комбинаций, чтобы слово из 12 гласных
    не породило миллионы строк.
    """
    # Для каждого символа берём список его возможных замен (или сам символ).
    choices = [LEET_MAP.get(ch, [ch]) for ch in word.lower()]

    results = []
    for combo in itertools.product(*choices):  # <- тут и живёт комбинаторный взрыв
        results.append("".join(combo))
        if len(results) >= max_variants:
            break
    return results


# ---------------------------------------------------------------------------
# 3. РЕГУЛЯРНЫЕ ВЫРАЖЕНИЯ — извлечение «значимых» токенов из сырого ввода
# ---------------------------------------------------------------------------
# Пользователь вводит мусор: "Дмитрий Петров, 15.03.2001, ник @dimka_gaming".
# Регэкспы вытаскивают оттуда структурированные куски.

# \d{4} — ровно 4 цифры подряд. Ищем год рождения внутри любой даты.
YEAR_RE = re.compile(r"\b(19\d{2}|20\d{2})\b")

# \d{1,2} — одна-две цифры: день и месяц.
DAY_MONTH_RE = re.compile(r"\b(\d{1,2})[.\-/](\d{1,2})\b")

# [A-Za-zА-Яа-я]{3,} — последовательности букв длиной 3+ (отсекаем предлоги/шум).
WORD_RE = re.compile(r"[A-Za-zА-Яа-я]{3,}")


def extract_tokens(raw: str):
    """Разбирает свободный текст на базовые токены с помощью регэкспов."""
    tokens = set()

    # Слова (имена, ники, увлечения).
    for m in WORD_RE.findall(raw):
        tokens.add(m.lower())

    # Годы целиком (1900-2099).
    years = set(YEAR_RE.findall(raw))

    # Дни/месяцы из дат — часто идут в хвост пароля.
    for day, month in DAY_MONTH_RE.findall(raw):
        tokens.add(day.zfill(2))      # "5" -> "05"
        tokens.add(month.zfill(2))

    return tokens, years


# ---------------------------------------------------------------------------
# 4. СУФФИКСЫ И КАПИТАЛИЗАЦИЯ
# ---------------------------------------------------------------------------

def common_suffixes(years):
    """
    Типовые «хвосты», которые люди лепят ради требования «цифра + спецсимвол».
    Это не делает пароль стойким — делает его ПРЕДСКАЗУЕМЫМ.
    """
    suffixes = ["", "1", "123", "!", "123!", "@", "2024", "2025"]
    # Плюс годы рождения, найденные в данных, и их 2-значные формы.
    for y in years:
        suffixes.append(y)
        suffixes.append(y[2:])   # "2001" -> "01"
    return suffixes


def case_variants(word: str):
    """Три самых частых варианта регистра: как есть, Capitalized, UPPER."""
    return {word, word.capitalize(), word.upper()}


# ---------------------------------------------------------------------------
# 5. СБОРКА СЛОВАРЯ
# ---------------------------------------------------------------------------

def build_wordlist(raw_input: str,
                   min_len: int = 6,
                   max_len: int = 20,
                   leet: bool = True) -> list:
    """
    Главный конвейер:
      сырой текст -> токены (regex) -> транслит -> регистр -> leet -> суффиксы
    На выходе — отсортированный уникальный список кандидатов.
    """
    tokens, years = extract_tokens(raw_input)

    # Добавляем транслитерированные версии кириллических токенов.
    base_words = set()
    for t in tokens:
        base_words.add(t)
        tr = transliterate(t)
        if tr and tr != t:
            base_words.add(tr)

    suffixes = common_suffixes(years)
    candidates = set()

    for word in base_words:
        # Варианты регистра для базового слова.
        for cased in case_variants(word):
            # Leet-мутации (или только само слово, если leet выключен).
            leeted = leet_variants(cased) if leet else [cased]
            for variant in leeted:
                # К каждому варианту приклеиваем каждый суффикс.
                # Снова комбинаторика: |base| * |case| * |leet| * |suffix|.
                for suf in suffixes:
                    pw = variant + suf
                    if min_len <= len(pw) <= max_len:
                        candidates.add(pw)

    return sorted(candidates)


# ---------------------------------------------------------------------------
# 6. ТОЧКА ВХОДА
# ---------------------------------------------------------------------------

def main():
    print("=== Аудит предсказуемости пароля (вводи СВОИ данные) ===\n")
    print("Введи всё, что помнишь: имя, дату рождения, ник, увлечения.")
    print("Пример: Дмитрий Петров 15.03.2001 dimka gaming cska\n")

    raw = input("Данные: ").strip()
    if not raw:
        print("Пусто. Нечего анализировать.")
        return

    wordlist = build_wordlist(raw)

    print(f"\nСгенерировано кандидатов: {len(wordlist)}")
    print("Первые 30 для наглядности:\n")
    for pw in wordlist[:30]:
        print("  ", pw)

    # Можно выгрузить в файл и потом проверить против ХЕШЕЙ СВОИХ тестовых паролей.
    out = "my_candidates.txt"
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(wordlist))
    print(f"\nПолный список записан в {out}")
    print("\nВывод простой: если твой реальный пароль здесь — он построен по шаблону.")


if __name__ == "__main__":
    main()
